function sanitizeAudit(text) {
  let x = String(text || '').replace(/<think>[\s\S]*?<\/think>/gi, '').replace(/<\/?think>/gi, '').replace(/```[a-z]*\n?/gi, '');
  const a = x.indexOf('{'), b = x.lastIndexOf('}');
  if (a < 0 || b <= a) return null;
  let o = null;
  try { o = JSON.parse(x.slice(a, b + 1)); } catch (e) { return null; }
  if (!o || typeof o !== 'object' || (o.agree !== true && o.agree !== false)) return null;   /* null/غير مفهوم = ما نحكمش */
  const str = function (v, n) { return typeof v === 'string' ? v.replace(/\s+/g, ' ').trim().slice(0, n) : ''; };
  const v = { agree: o.agree, final: str(typeof o.final === 'number' ? String(o.final) : o.final, 200), where: str(o.where, 300) };
  if (!v.agree && !v.final && !v.where) return null;
  return v;
}

/* AUDIT-THEORY: نص المراجعة لجزء — المسألة المعلّمة: نصها + الشرح؛ السؤال النظري: السؤال + الاختيارات + الإجابة المقترحة + الشرح */
function auditInput(p) {
  if (p._pb) return { prob: p._pb, sol: p.explain.slice(0, 5000) };
  const opts = Array.isArray(p.opts) ? p.opts : [];
  let prob = p.q;
  if (opts.length) prob += '\nالاختيارات:\n' + opts.map(function (o, i) { return (i + 1) + ') ' + o; }).join('\n');
  const picked = Array.isArray(p.ai) && p.ai.length ? p.ai.map(function (i) { return opts[i]; }).filter(Boolean).join(' + ') : '';
  const ans = picked || p.ans || '';
  return { prob: prob, sol: (ans ? 'الإجابة المقترحة: ' + ans + '\n\n' : '') + p.explain.slice(0, 4500) };
}
