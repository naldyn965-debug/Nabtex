function fsVal(f) {
  if (!f) return null;
  if (f.timestampValue) return Date.parse(f.timestampValue);
  if (f.integerValue !== undefined) return parseInt(f.integerValue, 10);
  if (f.stringValue !== undefined) return f.stringValue;
  return null;
}
/* {} = المستند مش موجود · null = فشلت القراءة */
